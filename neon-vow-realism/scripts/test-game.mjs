import assert from "node:assert/strict";
import {createGame,tick,keyframe,MAX_LEVEL,obstacles} from "../src/simulation.mjs";
const blank=()=>[{x:0,z:0,fire:false,dash:0,special:0},{x:0,z:0,fire:false,dash:0,special:0}];
let checks=0;
const check=(cond,msg)=>{assert.ok(cond,msg);checks++};
const s=createGame(1,true);
check(s.players.length===2,"two playable heroes");
check(s.enemies.length>=3,"enemies spawn");
check(s.phase==="fight","initial combat");
check(obstacles(1).length>=5,"cover placed");
let moved=s.players[1].x;
let i=blank();i[1].x=1;
tick(s,i,.033);
check(s.players[1].x>moved,"guest's movement must work");
s.players[0].x=s.enemies[0].x;s.players[0].z=s.enemies[0].z+1;
const target=s.enemies[0],before=target.hp;
i=blank();i[0].fire=true;
tick(s,i,.033);
check(target.hp<before,"male attack lands on target");
s.players[0].cool=0;
s.players[0].energy=100;
i=blank();i[0].special=3;
const prevEnergy=s.players[0].energy;
const fx=tick(s,i,.033);
check(fx.some(e=>e.kind==="pulse"),"special skill event fires");
check(s.players[0].energy<prevEnergy&&s.players[0].energy>=prevEnergy-60,"special consumes charge, with energy rewarded for kills");
s.enemies.length=0;s.phase="gate";
s.players[0].x=s.players[1].x=0;
s.players[0].z=s.players[1].z=s.gateZ;
for(let n=0;n<45;n++)tick(s,blank(),.035);
check(s.sector===1,"cooperative gate advances sectors");
check(s.enemies.length>0,"next wave respawns");
s.enemies.length=0;s.phase="gate";s.players.forEach(p=>{p.x=0;p.z=s.gateZ;});
for(let n=0;n<45;n++)tick(s,blank(),.035);
check(s.sector===2,"second gate opens boss sector");
check(s.enemies.some(e=>e.type==="boss"),"boss spawns");
s.enemies.length=0;s.phase="gate";s.players.forEach(p=>{p.x=0;p.z=s.gateZ;});
for(let n=0;n<45;n++)tick(s,blank(),.035);
check(s.phase==="victory","win state reachable");
const s2=createGame(1,true);s2.enemies=[];s2.phase="gate";
s2.players[1].down=true;s2.players[1].hp=0;
s2.players[1].x=s2.players[0].x;s2.players[1].z=s2.players[0].z;
for(let n=0;n<70;n++)tick(s2,blank(),.035);
check(!s2.players[1].down&&s2.players[1].hp>0,"nearby teammate gets rescued");
const s3=createGame(3,false);
s3.players[0].x=0;s3.players[0].z=-9;
const oldZ=s3.players[0].z;
let soloInput=blank();soloInput[0].z=-1;soloInput[0].dash=1;
tick(s3,soloInput,.035);
check(s3.players[0].z<oldZ-.1,"dash accelerates movement");
check(s3.players[0].dashCooldown>2,"dash has cooldown");
check(MAX_LEVEL===12,"12-level campaign");
check(JSON.stringify(keyframe(s3)).length<25000,"network snapshot reasonably compact");
console.log("PASS",checks,"simulation assertions, including 2-player co-op logic, melee, EMP, boss, gates, rescues, dash.");
